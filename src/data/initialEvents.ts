export function formatImagePath(path: string): string {
  if (!path) return '';
  // Ensure relative path without leading slash so it resolves properly on Vercel and GitHub Pages
  const relativePath = path.startsWith('/') ? path.slice(1) : path;
  return encodeURI(relativePath);
}

export const INITIAL_TIMELINE_EVENTS = EVENTS_PT.map((evt) => ({
  ...evt,
  imageUrl: formatImagePath(evt.imageUrl),
}));

export function getTimelineEvents(lang: Language): TimelineEvent[] {
  const baseEvents = lang === 'en' ? EVENTS_EN : EVENTS_PT;
  return baseEvents.map((evt) => ({
    ...evt,
    imageUrl: formatImagePath(evt.imageUrl),
  }));
}
